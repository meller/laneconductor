// The documents behind the board's track detail (track AM-10106, Phase 5d Task 7). The pure parts:
// which tracks get a docs file, what a docs file holds (with the privacy scan applied), how the
// GitHub link for a done track is derived. Reading files and writing the site is lc-board.mjs's job.
import { scanText } from './scan.mjs';
import { resolveTrack } from './tracks.mjs';

export const MAX_DOC_CHARS = 60000;
export const MAX_DOCS = 200;
export const TRUNCATED_NOTE = '\n\n[truncated]';
/** The fields of a docs file, in order, and the file each one comes from. */
export const DOC_FIELDS = [['index', 'index.md'], ['plan', 'plan.md'], ['spec', 'spec.md'], ['test', 'test.md']];
export const CONVERSATION_FIELD = ['conversation', 'conversation.md'];
// Track AM-10155: explain.md (generated by lc-explain.mjs: where the agent's time and tokens went) is one more document, shown as the "Agent run" tab. Optional like the conversation: no file, no key, no tab.
export const EXPLAIN_FIELD = ['explain', 'explain.md'];

export const capText = (text) => (text.length > MAX_DOC_CHARS ? `${text.slice(0, MAX_DOC_CHARS)}${TRUNCATED_NOTE}` : text);

/**
 * Which tracks get a docs file: live, not done, not archived, and with a folder that is the one
 * folder for its number (a number shared by two live folders is flagged by the board's check and
 * gets no docs, because `docs/<number>.json` could not tell them apart). At most `max` are kept:
 * the oldest backlog tracks (lowest number) are dropped first, then the lowest-numbered of the rest.
 * @param {{ tracks: { number: number, folder: string, lane: string | null, archived?: boolean }[] }} board
 * @returns {{ keep: { number: number, folder: string }[], dropped: number }}
 */
export function selectDocTracks(board, { max = MAX_DOCS } = {}) {
  const live = board.tracks.filter((t) => !t.archived);
  const folders = live.map((t) => t.folder);
  const candidates = live.filter((t) => {
    if (t.lane === 'done') return false;
    try { return resolveTrack(folders, String(t.number)) === t.folder; } catch { return false; }
  });
  const dropOrder = [...candidates].sort((a, b) => (b.lane === 'backlog') - (a.lane === 'backlog') || a.number - b.number || a.folder.localeCompare(b.folder));
  const dropped = Math.max(0, candidates.length - max);
  const dropSet = new Set(dropOrder.slice(0, dropped).map((t) => t.folder));
  return { keep: candidates.filter((t) => !dropSet.has(t.folder)).map((t) => ({ number: t.number, folder: t.folder })), dropped };
}

// ---- Finished tracks (track AM-10155, D11). Their documents are packed into a few shard files `docs-done/<k>.json`, { k, docs: { "<number>": <the same doc as docs/<number>.json> } },
// so a project with hundreds of finished tracks stays far below the site's file limit. board.json says which shard holds a finished track (`ds`); the page loads the shard when one is opened.
export const DONE_SHARD_TRACKS = 20;
export const DONE_SHARD_BYTES = 1000000;
/** At most this many shards are published; the oldest (lowest numbers) are left out beyond it, so live tracks always keep half of the file limit. */
export const MAX_DONE_SHARDS = MAX_DOCS / 2;

/**
 * Which finished tracks get a document: the same rule as a live track (not archived, the number resolves to one folder), in number order.
 * @param {{ tracks: { number: number, folder: string, lane: string | null, archived?: boolean }[] }} board
 * @returns {{ number: number, folder: string }[]}
 */
export function selectDoneTracks(board) {
  const live = board.tracks.filter((t) => !t.archived);
  const folders = live.map((t) => t.folder);
  return live
    .filter((t) => {
      if (t.lane !== 'done') return false;
      try { return resolveTrack(folders, String(t.number)) === t.folder; } catch { return false; }
    })
    .sort((a, b) => a.number - b.number || a.folder.localeCompare(b.folder))
    .map((t) => ({ number: t.number, folder: t.folder }));
}

/**
 * Packs finished-track documents (already built with `buildDoc`, so capped and scanned) into shards, in number order: a shard is closed when it holds
 * `maxTracks` tracks or when the next document would take it past `maxBytes`. A document larger than `maxBytes` gets a shard of its own.
 * @param {{ number: number, folder: string, doc: object }[]} items
 * @returns {{ k: number, docs: Record<string, object> }[]} shards numbered from 1
 */
export function packShards(items, { maxTracks = DONE_SHARD_TRACKS, maxBytes = DONE_SHARD_BYTES } = {}) {
  const shards = [];
  let cur = null;
  let bytes = 0;
  for (const it of [...items].sort((a, b) => a.number - b.number || a.folder.localeCompare(b.folder))) {
    const size = Buffer.byteLength(JSON.stringify(it.doc)) + String(it.number).length + 4;
    if (cur && (Object.keys(cur.docs).length >= maxTracks || bytes + size > maxBytes)) cur = null;
    if (!cur) { cur = { k: shards.length + 1, docs: {} }; shards.push(cur); bytes = 40; }
    cur.docs[String(it.number)] = it.doc;
    bytes += size;
  }
  return shards;
}

const pluralMatches = (n) => `${n} match${n === 1 ? '' : 'es'}`;

/**
 * One docs file. `texts` maps field name -> file text (null/undefined when the file does not exist).
 * A file with any scan match is NOT embedded: its field is left out and `withheld[field]` says why
 * (a count, never the matched text). `conversation` is only read when `includeConversation` is true.
 * @returns {{ doc: object, withheld: { field: string, file: string, matches: number, lines: number[] }[] }}
 */
export function buildDoc({ number, folder, texts, includeConversation = false }) {
  const doc = { n: number, folder };
  const withheldDoc = {};
  const withheld = [];
  const fields = [...DOC_FIELDS, ...(includeConversation ? [CONVERSATION_FIELD] : []), ...(texts.explain !== undefined && texts.explain !== null ? [EXPLAIN_FIELD] : [])];
  for (const [field, file] of fields) {
    const text = texts[field];
    if (field === 'conversation' && (text === null || text === undefined)) continue; // no conversation file: no tab
    if (text === null || text === undefined || text === '') { if (field !== 'conversation') doc[field] = ''; continue; }
    const hits = scanText(text);
    if (hits.length) {
      withheldDoc[field] = `possible secret or personal data (${pluralMatches(hits.length)})`;
      withheld.push({ field, file, matches: hits.length, lines: [...new Set(hits.map((h) => h.line))].slice(0, 10) });
      continue;
    }
    doc[field] = capText(text);
  }
  if (withheld.length) doc.withheld = withheldDoc;
  return { doc, withheld };
}

/**
 * `https://github.com/<owner>/<repo>` from a git remote URL (ssh scp-style, ssh://, https, with or
 * without credentials or a .git suffix), or null when it is not a github.com remote.
 */
export function githubBase(remote) {
  const s = String(remote ?? '').trim();
  const m = /^(?:git@github\.com:|ssh:\/\/(?:[^@/]+@)?github\.com(?::\d+)?\/|https?:\/\/(?:[^@/]+@)?github\.com\/|git:\/\/github\.com\/)([A-Za-z0-9_.-]+)\/([A-Za-z0-9_.-]+?)(?:\.git)?\/?$/i.exec(s);
  return m ? `https://github.com/${m[1]}/${m[2]}` : null;
}

/** The GitHub page of one track folder on `branch`. Folder names are path-encoded. */
export const githubFolderUrl = (base, branch, folder) => `${base}/tree/${branch.split('/').map(encodeURIComponent).join('/')}/conductor/tracks/${encodeURIComponent(folder)}`;

// ---- The project definition (track AM-10115, the Project drawer). One tab per definition that exists, read from the project's
// conductor folder at generation time. Each tab is its own file `ctx/<key>.json` next to board.json, fetched when the tab is first
// opened, and goes through the SAME privacy scan as a track document. `.laneconductor.json` is never a source: it holds personal
// settings (an artifact URL, possibly tokens), so no tab reads it.
/** The tabs in order. `files` are relative to conductor/; `dir` adds the markdown files of one sub-folder (code styleguides). */
export const PROJECT_TABS = [
  { k: 'overview', t: 'Overview', files: ['product.md'] },
  { k: 'tech-stack', t: 'Tech stack', files: ['tech-stack.md'] },
  { k: 'workflow', t: 'Workflow', files: ['workflow.md'] },
  { k: 'quality-gate', t: 'Quality gate', files: ['quality-gate.md'] },
  { k: 'kpis', t: 'KPIs', files: ['kpis.md'] },
  { k: 'guidelines', t: 'Guidelines', files: ['product-guidelines.md', 'design-language.md'], dir: 'code_styleguides' },
  { k: 'stories', t: 'Stories', files: ['user-stories.md'] },
  { k: 'deployment', t: 'Deployment', files: ['deployment-stack.md'] },
  // Track AM-10155: generated by `lc-explain.mjs` from every track's explain.md, finished tracks included.
  { k: 'statistics', t: 'Statistics', files: ['statistics.md'] },
];
/**
 * Track AM-10155 (D7): the Statistics tab marks every finished track that has no explain.md as "no statistics recorded", worked out when the
 * board is read (the generated statistics.md only knows the tracks that have a file). Text unchanged when there is nothing to mark.
 * @param {string} text the text of statistics.md
 * @param {{ number: number, folder: string, lane: string | null, archived?: boolean }[]} tracks board tracks
 * @param {Set<string>} withExplain folders that have an explain.md
 */
export function markUnrecordedStatistics(text, tracks, withExplain) {
  const rows = tracks.filter((t) => !t.archived && t.lane === 'done' && !withExplain.has(t.folder)).sort((a, b) => a.number - b.number);
  if (!rows.length) return text;
  return `${text.replace(/\s+$/, '')}\n\n## Finished tracks with no statistics recorded\n\n| Track | Statistics |\n| --- | --- |\n${rows.map((t) => `| ${t.number} | no statistics recorded |`).join('\n')}\n`;
}

/** At most this many files of the styleguides folder go into the Guidelines tab. */
export const MAX_STYLEGUIDES = 6;

// Lines the scaffold (src/newproject/scaffold.mjs) writes when an answer was not given, plus the fixed checklist text of an
// untouched quality gate. A file whose every line (headings and blank lines aside) is one of these has nothing to read yet.
const PLACEHOLDER_LINES = [
  /^\(placeholder\b[^)]*\)$/i,
  /^\(not decided yet\)$/i,
  /^- [^:]{1,40}: \(not decided yet\)$/i,
  /^None stated\.$/,
  /^TODO\b/,
  /^Flow: \(to be written\)$/,
  /^\|[\s|]*\(none set yet\)[\s|]*$/,
  /^\|[\s:|-]*\|$/, // a table separator row
  /^\| (?:ID \| )?Metric \| Target \| Time Horizon \| (?:Status|Focus) \| Notes \|$/,
  /^Tracks with `\*\*Maps To\*\*` referencing a metric above/,
  /^\(No verification commands exist yet/,
  /^>/,
  /^- \[ \] (?:Architecture alignment|Readability|No stubs)\b/,
  /^- Status: PENDING\b/,
  /^- Reviewer: \(/,
  /^- Date: \(/,
];
/** True when the text is empty or only the untouched scaffold placeholder text. */
export function isPlaceholderOnly(text) {
  if (typeof text !== 'string') return true;
  const lines = text.split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !/^#{1,6}(\s|$)/.test(l));
  return lines.every((l) => PLACEHOLDER_LINES.some((re) => re.test(l)));
}

const reasonOf = (hits) => `possible secret or personal data (${pluralMatches(hits.length)})`;

/**
 * The tab list and the ctx files of the project definition.
 * @param {{ texts: Record<string, string|null|undefined>, hasFlow?: boolean, deploys?: { md: string, envs: string[] } | null }} a
 *   `texts`: file text by path relative to conductor/ (`product.md`, `code_styleguides/javascript.md`); `hasFlow`: workflow.json gave lanes to
 *   draw (the Workflow tab exists even with no workflow.md); `deploys` (track AM-10156): the deploy records as Markdown and their environment
 *   names (deploysForBoard in deploys.mjs, scanned record by record). With it the Deployment tab exists even with no deployment-stack.md, shows
 *   the records first, and the tab doc gets `deploys` (the environment names, for the Copy buttons).
 * @returns {{ tabs: { k: string, t: string, f: string }[], ctx: { name: string, doc: object }[], withheld: { file: string, matches: number, lines: number[] }[] }}
 */
export function buildProjectDocs({ texts = {}, hasFlow = false, deploys = null } = {}) {
  const tabs = [];
  const ctx = [];
  const withheld = [];
  for (const tab of PROJECT_TABS) {
    const names = [...tab.files];
    if (tab.dir) names.push(...Object.keys(texts).filter((n) => n.startsWith(`${tab.dir}/`) && /\.md$/i.test(n)).sort().slice(0, MAX_STYLEGUIDES));
    const real = names.filter((n) => typeof texts[n] === 'string' && !isPlaceholderOnly(texts[n]));
    const recs = tab.k === 'deployment' && deploys && deploys.md ? deploys : null;
    if (!real.length && !(tab.k === 'workflow' && hasFlow) && !recs) continue;
    const parts = real.map((n) => {
      const hits = scanText(texts[n]);
      if (hits.length) withheld.push({ file: n, matches: hits.length, lines: [...new Set(hits.map((h) => h.line))].slice(0, 10) });
      return { n, hits, text: texts[n] };
    });
    const doc = { k: tab.k, t: tab.t };
    if (parts.length && parts.every((p) => p.hits.length)) {
      doc.withheld = parts.length === 1 ? reasonOf(parts[0].hits) : `possible secret or personal data (${pluralMatches(parts.reduce((s, p) => s + p.hits.length, 0))} in ${parts.length} files)`;
    } else if (parts.length === 1) {
      doc.md = capText(parts[0].text);
    } else if (parts.length > 1) {
      // One tab, several files: a section each; a file with a match gets a note in its place.
      doc.md = capText(parts.map((p) => `## ${p.n.replace(/^.*\//, '')}\n\n${p.hits.length ? `*withheld: ${reasonOf(p.hits)}; read it in the repository.*` : p.text.trim()}\n`).join('\n'));
    } else {
      doc.md = ''; // the Workflow tab with only a drawing
    }
    if (recs) {
      // The records come first (what is live); a stack file that was withheld is named after them, never hiding them.
      doc.md = `${recs.md}${doc.withheld ? `\n*withheld: ${doc.withheld}; read deployment-stack.md in the repository.*\n` : doc.md ? `\n${doc.md}` : ''}`;
      delete doc.withheld;
      doc.deploys = recs.envs;
    }
    tabs.push({ k: tab.k, t: tab.t, f: `ctx/${tab.k}.json` });
    ctx.push({ name: `ctx/${tab.k}.json`, doc });
  }
  return { tabs, ctx, withheld };
}
