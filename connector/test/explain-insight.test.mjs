test('TC-18: a quiet synthetic explain says nothing unusual and lists no rule', () => {
  const body = insight(quiet());
  assert.match(body, /What to look at/);
  assert.match(body, /Nothing unusual/);
  for (const word of ['sub-agent or a fresh session', 'upper bound', 'more than once', 'more than 30 minutes', 'slowest step', 'waiting for a person']) assert.ok(!body.includes(word), `quiet: ${word}`);
});

// Each rule: a variation that makes it fire, one that stays just under, and the words it says.
const RULES = [
  { name: 'a long main session', fire: { firstContext: 450000, sub: { responses: 2, output: 100 } }, edge: { firstContext: 400000, sub: { responses: 5, output: 100 } }, calm: [{ firstContext: 399999, sub: { responses: 0, output: 0 } }, { firstContext: 450000, sub: { responses: 6, output: 100 } }], word: 'sub-agent or a fresh session' },
  { name: 'a lane run with no claim commit', fire: { claimed: false }, calm: [{ claimed: true }], word: 'upper bound' },
  { name: 'a lane run never closed', fire: { open: true }, calm: [{ open: false }], word: 'upper bound' },
  { name: 'files read more than once', fire: { repeatedReads: 3 }, calm: [{ repeatedReads: 0 }], word: 'more than once' },
  { name: 'gaps of more than 30 minutes', fire: { gapsOver30: 2 }, calm: [{ gapsOver30: 0 }], word: 'more than 30 minutes' },
  { name: 'a slowest step of 5 minutes', fire: { slowest: [{ tool: 'Bash', ms: 5 * MIN, at: '2026-11-20T10:12:00.000Z' }] }, calm: [{ slowest: [{ tool: 'Bash', ms: 5 * MIN - 1000, at: '2026-11-20T10:12:00.000Z' }] }], word: 'slowest step' },
  { name: 'most of the wall time was a person', fire: { humanMs: 48 * MIN }, calm: [{ humanMs: 47 * MIN }], word: 'waiting for a person', inTime: true },
];
for (const rule of RULES) {
  test(`TC-18: rule fires and stays quiet: ${rule.name}`, () => {
    const fired = insight([run(rule.fire)]);
    assert.ok(fired.includes(rule.word), `fires: ${rule.word}`);
    if (!rule.inTime) assert.ok(!fired.includes('Nothing unusual'), 'a fired rule removes the nothing-unusual line');
    if (rule.edge) assert.ok(insight([run(rule.edge)]).includes(rule.word), 'the limit itself fires');
    for (const calm of rule.calm) assert.ok(!insight([run(calm)]).includes(rule.word), `stays quiet for ${JSON.stringify(calm)}`);
  });
}

