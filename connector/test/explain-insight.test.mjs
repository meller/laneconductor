// Track AM-10155 Phase 7 (D13, D14): the insight that explain.md and statistics.md open with. Synthetic results only; the insight is
// worked out from the numbers with fixed rules (no model) and never carries content.
//   TC-18 the rules of D13 each fire and each stay quiet; "Nothing unusual" when none fires
//   TC-19 statistics.md opens with its own insight and the explain files read back give the same tables
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { renderExplain, renderStatistics, parseExplain, renderInsight, readExplains } from '../src/explain.mjs';
import { markUnrecordedStatistics } from '../src/board-docs.mjs';
import { makeRepo, writeFile, rm } from './helpers/repo.mjs';

const MIN = 60000;
const NOW = '2026-11-22T08:00:00.000Z';

const run = (over = {}) => {
  const wallMs = over.wallMs ?? 60 * MIN;
  const humanMs = over.humanMs ?? 0;
  return {
    lane: 'implement', start: '2026-11-20T10:00:00.000Z', end: '2026-11-20T11:00:00.000Z', claimed: true, open: false, endState: 'success',
    wallMs, humanMs, agentMs: wallMs - humanMs, responses: 20, tokens: { output: 2000, fresh: 20, cacheCreated: 4000, cacheRead: 600000 },
    tools: { Read: 4, Bash: 3 }, sub: { responses: 10, output: 900 }, firstContext: 100000, subStarts: [20000, 30000], repeatedReads: 0,
    models: { m: 20 }, efforts: { medium: 20 }, thinking: { tokens: 0, recorded: 0, output: 0 }, path: '',
    slowest: [{ tool: 'Read', ms: 40000, at: '2026-11-20T10:10:00.000Z' }], gapsOver30: 0, asks: { count: 0, ms: 0 }, ...over,
  };
};
const result = (runs, phases = []) => ({ track: { number: 777, folder: 'AM-777-demo-track' }, generatedAt: NOW, runs, phases, none: { responses: 0, output: 0 }, skipped: { otherTrack: 0, outsideRepo: 0 }, sources: { mainFiles: 1, subFiles: 1, sessions: ['11111111'] } });
const insightOf = (text) => /^## Insight\n([\s\S]*?)(?=^## |^> |^Generated: )/m.exec(text)?.[1] ?? null;
const insight = (runs, phases) => insightOf(renderExplain(result(runs, phases), { now: NOW }));
const quiet = () => [run()];

test('TC-18: explain.md has ## Insight right after the short plan and Details (Phase 9), before the generated-by note, labelled as rule-based', () => {
  const text = renderExplain(result(quiet()), { now: NOW });
  const lines = text.split('\n');
  assert.equal(lines[0], '# Agent run: AM-777-demo-track');
  assert.equal(lines[1], '');
  assert.equal(lines[2], '## Short plan', 'Phase 9 (D19): the short plan comes first');
  assert.deepEqual(lines.filter((l) => l.startsWith('## ')).slice(0, 3), ['## Short plan', '## Details', '## Insight']);
  assert.ok(text.indexOf('## Insight') < text.indexOf('> Generated by'), 'the insight comes before the note');
  assert.ok(text.indexOf('## Insight') < text.indexOf('## Lane runs'));
  const body = insightOf(text);
  assert.match(body, /rule-based/);
  assert.match(body, /not an opinion of a model/);
  assert.match(text, /^> Generated by lc-explain\.mjs/m, 'the generated-by note is still there');
  assert.match(text, /^## Lane runs$/m);
});

