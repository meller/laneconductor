// ---- TC-19 (D14) ----
const explainOf = (folder, runs, phases) => renderExplain({ ...result(runs, phases), track: { number: Number(/\d+/.exec(folder)[0]), folder } }, { now: NOW });
const stripInsight = (text) => text.replace(/^## Insight\n[\s\S]*?(?=^> Generated by)/m, '');

test('TC-19: the tables read back from an explain.md are the same with or without the insight section', () => {
  const runs = [run({ lane: 'plan', wallMs: 30 * MIN, humanMs: 5 * MIN }), run({ wallMs: 120 * MIN, humanMs: 40 * MIN, claimed: false })];
  const phases = [{ label: 'Phase 1: First', key: 'Phase 1', wallMs: 60 * MIN, humanMs: 40 * MIN, agentMs: 20 * MIN, responses: 12, tokens: { output: 1200, fresh: 12, cacheCreated: 2400, cacheRead: 36000 }, tools: { Read: 5 }, sub: { responses: 0, output: 0 }, models: { m: 1 }, efforts: { medium: 1 }, thinking: { tokens: 0, recorded: 0, output: 0 }, path: '', tasks: 2 }];
  const withIt = renderExplain(result(runs, phases), { now: NOW });
  assert.ok(withIt.includes('## Insight'));
  const without = stripInsight(withIt);
  assert.ok(!without.includes('## Insight'));
  assert.deepEqual(parseExplain(withIt), parseExplain(without));
  assert.equal(parseExplain(withIt).runs.length, 2);
  assert.equal(parseExplain(withIt).phases.length, 1);
});

const stats = (items) => renderStatistics(items, { now: NOW });
const track = (n, runs) => ({ folder: `AM-${n}-t${n}`, text: explainOf(`AM-${n}-t${n}`, runs) });

test('TC-19: statistics.md opens with its own ## Insight right after the title: counts, highest ratio, most human waiting, totals', () => {
  const a = track(801, [run({ tokens: { output: 1000, fresh: 1, cacheCreated: 1, cacheRead: 100000 }, wallMs: 100 * MIN, humanMs: 10 * MIN })]);
  const b = track(802, [run({ tokens: { output: 1000, fresh: 1, cacheCreated: 1, cacheRead: 500000 }, wallMs: 100 * MIN, humanMs: 90 * MIN })]);
  const c = track(803, [run({ tokens: { output: 2000, fresh: 1, cacheCreated: 1, cacheRead: 100000 }, wallMs: 100 * MIN, humanMs: 0 })]);
  const text = stats([a, b, c]);
  const lines = text.split('\n');
  assert.equal(lines[0], '# Agent run statistics');
  assert.equal(lines[2], '## Insight');
  assert.ok(text.indexOf('## Insight') < text.indexOf('## Tracks'));
  const body = /^## Insight\n([\s\S]*?)^## Tracks/m.exec(text)[1];
  assert.match(body, /rule-based/);
  assert.match(body, /3 tracks have statistics/);
  assert.match(body, /Highest cache-read ratio: AM-802 \(500 times/);
  assert.match(body, /Most human waiting: AM-802 \(1h 30m, 90% of its wall time\)/);
  assert.match(body, /4,000 tokens written/);
  assert.match(body, /700,000 tokens read from cache/);
  assert.match(text, /^## Tracks$/m);
  assert.match(text, /^\| AM-801 \|/m);
});

test('TC-19: no explain yet, one track, and no human waiting stay plain', () => {
  assert.match(stats([]), /## Insight/);
  assert.match(stats([]), /No track has statistics yet/);
  const one = stats([track(801, [run({ humanMs: 0 })])]);
  assert.match(one, /1 track has statistics/);
  assert.ok(!/Most human waiting/.test(one), 'no human time, no claim');
  assert.ok(!/NaN|Infinity/.test(one));
});

test('TC-19: statistics tables are unchanged by the insight, readExplains reads the files with the section, and the board marks unrecorded finished tracks as before', () => {
  const repo = makeRepo({ prefix: 'lc-insight-' });
  try {
    for (const n of [801, 802]) writeFile(repo, `conductor/tracks/AM-${n}-t${n}/explain.md`, explainOf(`AM-${n}-t${n}`, [run({ wallMs: n === 801 ? 60 * MIN : 30 * MIN })]));
    const items = readExplains(repo);
    assert.equal(items.length, 2);
    assert.ok(items.every((i) => i.text.includes('## Insight')));
    const text = stats(items);
    const body = text.slice(text.indexOf('## Tracks'));
    assert.match(body, /^\| AM-801 \| 1 \| 1h 00m \|/m);
    assert.match(body, /^\| AM-802 \| 1 \| 30m \|/m);
    assert.match(body, /^\| implement \| 2 \| 1h 30m \|/m);
    const marked = markUnrecordedStatistics(text, [{ number: 803, lane: 'done', folder: 'AM-803-t803' }], new Set(['AM-801-t801', 'AM-802-t802']));
    assert.match(marked, /Finished tracks with no statistics recorded/);
    assert.match(marked, /\| 803 \| no statistics recorded \|/);
    assert.ok(marked.startsWith(text.replace(/\s+$/, '')), 'the insight and the tables stay as they were');
  } finally { rm(repo); }
});
