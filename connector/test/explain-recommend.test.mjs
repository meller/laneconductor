test('TC-24: the tables read back are the same with and without the new sections, and the statistics tables and the unrecorded marker are unchanged', () => {
  const runs = [run({ lane: 'plan', claimed: false }), run({ wallMs: 120 * MIN, humanMs: 40 * MIN })];
  const phases = [phase({ humanMs: 40 * MIN, wallMs: 60 * MIN, agentMs: 20 * MIN })];
  const withNew = explainOf('AM-801-t801', runs, phases);
  assert.ok(withNew.includes('## Recommendations') && withNew.includes('## Model use'));
  const without = withNew.replace(/^## Recommendations\n[\s\S]*?(?=^> Generated by)/m, '').replace(/^## Model use\n[\s\S]*?(?=^## )/m, '');
  assert.ok(!without.includes('## Recommendations') && !without.includes('## Model use'));
  assert.deepEqual(parseExplain(withNew), parseExplain(without));
  assert.equal(parseExplain(withNew).runs.length, 2);
  assert.equal(parseExplain(withNew).phases.length, 1);
  const tables = (t) => t.slice(t.indexOf('## Tracks'));
  const both = [{ folder: 'AM-801-t801', text: withNew }];
  const old = [{ folder: 'AM-801-t801', text: without }];
  assert.equal(tables(stats(both)), tables(stats(old)), 'the statistics tables do not depend on the new sections');
  const marked = markUnrecordedStatistics(stats(both), [{ number: 803, lane: 'done', folder: 'AM-803-t803' }], new Set(['AM-801-t801']));
  assert.match(marked, /\| 803 \| no statistics recorded \|/);
  assert.ok(marked.startsWith(stats(both).replace(/\s+$/, '')), 'the new section stays where it was');
});

