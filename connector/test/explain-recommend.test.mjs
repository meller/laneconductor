// Track AM-10155 Phase 8 (D15, D16, D18): the recommendations that explain.md and statistics.md carry after the insight. Synthetic results only.
//   TC-22 each rule fires and stays quiet at its limits; the suggested setup; the quiet case says "No change suggested"
//   TC-24 statistics.md recommendations across tracks, and the tables read back unchanged
//   TC-25 the recommendations hold numbers, model ids, tool names and times only
import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  renderExplain, renderStatistics, renderInsight, parseExplain, parseExplainExtras, recommend,
  LONG_CONTEXT, LOW_SUB_SHARE, MECHANICAL_SHARE, MIN_TOOL_CALLS, SMALL_REPLY_OUTPUT, BIG_REPLY_OUTPUT, THINKING_SHARE, SLOW_STEP_MS,
} from '../src/explain.mjs';
import { markUnrecordedStatistics } from '../src/board-docs.mjs';

const MIN = 60000;
const NOW = '2026-11-22T08:00:00.000Z';
const OPUS = 'claude-opus-5';
const SONNET = 'claude-sonnet-5-5';
const HAIKU = 'claude-haiku-4-5-20251001';

/** A quiet lane run: mechanical, small replies, a middle model, medium effort, no thinking, claimed, a short slowest step. */
const run = (over = {}) => ({
  lane: 'implement', start: '2026-11-20T10:00:00.000Z', end: '2026-11-20T11:00:00.000Z', claimed: true, open: false, endState: 'success',
  wallMs: 60 * MIN, humanMs: 0, agentMs: 60 * MIN, responses: 20, tokens: { output: 2000, fresh: 20, cacheCreated: 4000, cacheRead: 600000 },
  tools: { Read: 4, Bash: 3 }, sub: { responses: 10, output: 900 }, firstContext: 100000, subStarts: [20000, 30000], repeatedReads: 0,
  slowest: [{ tool: 'Read', ms: 40000, at: '2026-11-20T10:10:00.000Z' }], gapsOver30: 0, asks: { count: 0, ms: 0 },
  models: { [SONNET]: 20 }, efforts: { medium: 20 }, thinking: { tokens: 0, recorded: 20, output: 2000 }, path: 'Read x4, Bash x3', ...over,
});
const phase = (over = {}) => ({
  label: 'Phase 1: First', key: 'Phase 1', tasks: 2, wallMs: 30 * MIN, humanMs: 0, agentMs: 30 * MIN, responses: 10, tokens: { output: 1000, fresh: 10, cacheCreated: 2000, cacheRead: 30000 },
  tools: { Read: 4, Bash: 3 }, sub: { responses: 0, output: 0 }, models: { [SONNET]: 10 }, efforts: { medium: 10 }, thinking: { tokens: 0, recorded: 10, output: 1000 }, path: 'Read x4, Bash x3', ...over,
});
const result = (runs, phases = []) => ({ track: { number: 777, folder: 'AM-777-demo-track' }, generatedAt: NOW, runs, phases, none: { responses: 0, output: 0 }, skipped: { otherTrack: 0, outsideRepo: 0 }, sources: { mainFiles: 1, subFiles: 1, sessions: ['11111111'] } });
const rules = (runs, phases) => recommend(result(runs, phases)).items.map((i) => i.rule);
const sectionOf = (text) => /^## Recommendations\n([\s\S]*?)(?=^## |^> |^Generated: )/m.exec(text)?.[1] ?? null;
const reco = (runs, phases) => sectionOf(renderExplain(result(runs, phases), { now: NOW }));

test('TC-22: the thresholds are named constants with the values of D16', () => {
  assert.deepEqual([LONG_CONTEXT, LOW_SUB_SHARE, MECHANICAL_SHARE, THINKING_SHARE, SLOW_STEP_MS], [400000, 30, 80, 30, 5 * MIN]);
  // not in D16: the owner tunes these (the report lists them)
  assert.deepEqual([MIN_TOOL_CALLS, SMALL_REPLY_OUTPUT, BIG_REPLY_OUTPUT], [5, 400, 1500]);
});

test('TC-22: a quiet run says "No change suggested", fires no rule and gives no setup', () => {
  assert.deepEqual(rules([run()]), []);
  const body = reco([run()]);
  assert.match(body, /No change suggested/);
  assert.match(body, /Recommendation rules fired: 0/);
  assert.ok(!/Suggested setup/.test(body));
  assert.match(body, /rule-based suggestions/);
  assert.match(body, /not an opinion of a model/);
  assert.match(body, /no dollars and no promise of savings/);
  assert.match(body, /heuristic/);
});

test('TC-22: the recommendations come right after the insight and before the generated-by note, and no rule is missing from the heading order', () => {
  const text = renderExplain(result([run({ claimed: false })]), { now: NOW });
  const heads = text.split('\n').filter((l) => l.startsWith('## ')).slice(0, 3);
  assert.deepEqual(heads, ['## Insight', '## Recommendations', '## Lane runs']);
  assert.ok(text.indexOf('## Recommendations') < text.indexOf('> Generated by'));
});

// ---- rule 1: where to run (400,000 tokens of first-reply context, under 30 percent sub-agent replies) ----
test('TC-22: where to run fires at 400,000 tokens and stays quiet at 399,999', () => {
  const long = (firstContext, sub = 0) => run({ firstContext, sub: { responses: sub, output: 0 } });
  assert.deepEqual(rules([long(400000)]), ['where']);
  assert.deepEqual(rules([long(399999)]), []);
});

test('TC-22: where to run: under 30 percent of replies from sub-agents fires, 30 percent stays quiet (the same test as the insight)', () => {
  const share = (sub, of) => run({ firstContext: 500000, responses: of, sub: { responses: sub, output: 0 }, tokens: { output: 2000, fresh: 1, cacheCreated: 1, cacheRead: 1 } });
  assert.deepEqual(rules([share(29, 100)]), ['where']);
  assert.deepEqual(rules([share(30, 100)]), []);
  assert.deepEqual(rules([share(2, 10)]), ['where']);
  assert.deepEqual(rules([share(3, 10)]), []);
  // the insight and the recommendation never disagree on the same run, including at the rounding edge (29.6 percent rounds to 30)
  for (const [sub, of] of [[29, 100], [30, 100], [296, 1000], [295, 1000], [3, 10], [2, 10], [0, 0]]) {
    const x = share(sub, of);
    const insightFires = /sub-agent or a fresh session may do the long work/.test(renderInsight(result([x])).join('\n'));
    assert.equal(rules([x]).includes('where'), insightFires, `${sub} of ${of}`);
  }
});

test('TC-22: where to run names the run, its context, its share and the limit', () => {
  const body = reco([run({ firstContext: 646000, sub: { responses: 2, output: 10 } })]);
  assert.match(body, /Run the implement run starting 2026-11-20 10:00 in a sub-agent or a fresh session/);
  assert.match(body, /646,000 tokens of context \(limit 400,000\)/);
  assert.match(body, /10% of its replies came from sub-agents \(limit 30%\)/);
});

// ---- rule 2: which model ----
const mech = (calls, mechanical) => ({ Bash: mechanical, Agent: calls - mechanical });
test('TC-22: lighter model fires at 80 percent mechanical tool calls and stays quiet at 79 percent', () => {
  const opus = (tools) => run({ tools, models: { [OPUS]: 20 } });
  assert.deepEqual(rules([opus(mech(100, 80))]), ['lighter-model']);
  assert.deepEqual(rules([opus(mech(100, 79))]), []);
  assert.deepEqual(rules([opus(mech(5, 4))]), ['lighter-model'], 'exactly 80 percent of the minimum number of calls');
  assert.deepEqual(rules([opus(mech(4, 4))]), [], 'fewer calls than the minimum are too few to judge');
  const body = reco([opus(mech(100, 80))]);
  assert.match(body, /80% of 100 tool calls were shell, read or file edits \(limit 80%\)/);
  assert.match(body, /20 of 20 replies ran on claude-opus-5/);
});

test('TC-22: lighter model: small output per reply fires at the limit, one token more stays quiet', () => {
  const opus = (output) => run({ tools: mech(10, 10), models: { [OPUS]: 10 }, responses: 10, tokens: { output, fresh: 1, cacheCreated: 1, cacheRead: 1 }, thinking: { tokens: 0, recorded: 10, output } });
  assert.deepEqual(rules([opus(10 * SMALL_REPLY_OUTPUT)]), ['lighter-model']);
  assert.deepEqual(rules([opus(10 * SMALL_REPLY_OUTPUT + 1)]), []);
});

test('TC-22: lighter model only for the largest tier: sonnet, haiku, an unknown id and a placeholder stay quiet', () => {
  for (const models of [{ [SONNET]: 20 }, { [HAIKU]: 20 }, { 'claude-fable-5': 20 }, { synthetic: 20 }, { other: 20 }, { unknown: 20 }]) assert.deepEqual(rules([run({ tools: mech(10, 10), models })]), [], JSON.stringify(models));
  // the tier is that of the model with the most replies; a placeholder does not count as a model
  assert.deepEqual(rules([run({ tools: mech(10, 10), models: { synthetic: 15, [OPUS]: 5 } })]), ['lighter-model']);
});

test('TC-22: lighter model reads the phases of the implement lane, not the whole run', () => {
  const r = rules([run({ tools: { Agent: 10 }, models: { [OPUS]: 20 } })], [phase({ tools: mech(10, 10), models: { [OPUS]: 10 } }), phase({ label: 'Phase 2: Second', key: 'Phase 2', tools: { Agent: 10 }, models: { [OPUS]: 10 } })]);
  assert.deepEqual(r, ['lighter-model']);
  assert.match(sectionOf(renderExplain(result([run()], [phase({ tools: mech(10, 10), models: { [OPUS]: 10 } })]), { now: NOW })), /Phase 1: First: use a model one tier down \(sonnet\)/);
});

test('TC-22: larger model: a haiku phase with big replies or much thinking fires, a mechanical or larger-model phase stays quiet', () => {
  const small = (over) => run({ tools: { Agent: 10 }, models: { [HAIKU]: 20 }, ...over });
  const big = (output) => small({ responses: 10, tokens: { output, fresh: 1, cacheCreated: 1, cacheRead: 1 }, thinking: { tokens: 0, recorded: 10, output } });
  assert.deepEqual(rules([big(10 * BIG_REPLY_OUTPUT)]), ['larger-model']);
  assert.deepEqual(rules([big(10 * BIG_REPLY_OUTPUT - 1)]), []);
  assert.deepEqual(rules([small({ thinking: { tokens: 600, recorded: 20, output: 2000 } })]), ['larger-model'], '30 percent thinking');
  assert.deepEqual(rules([small({ thinking: { tokens: 599, recorded: 20, output: 2000 } })]), [], '29.95 percent');
  assert.deepEqual(rules([small({ models: { [SONNET]: 20 }, thinking: { tokens: 900, recorded: 20, output: 2000 } })]), []);
  assert.deepEqual(rules([run({ tools: mech(10, 10), models: { [HAIKU]: 20 }, thinking: { tokens: 900, recorded: 20, output: 2000 } })]), ['lower-effort'], 'a mechanical phase is not the case for a larger model; it is the case for a lower effort');
  assert.match(reco([big(10 * BIG_REPLY_OUTPUT)]), /keep or use a larger model \(sonnet or above\).*1,500 tokens written per reply, limit 1,500/);
});

