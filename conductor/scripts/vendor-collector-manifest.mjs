#!/usr/bin/env node
// conductor/scripts/vendor-collector-manifest.mjs
// Track 10061 (D4): mechanical ESM -> CommonJS transform of
// conductor/services/collector-manifest.mjs into cloud/functions/collector-manifest.js.
//
// Why a vendored copy exists at all: firebase.json sets
// functions.source: "cloud/functions", so the deployed function bundle
// contains ONLY that directory — it cannot `require()` anything under
// conductor/. The cloud function is also CommonJS while the rest of the repo
// is ESM. Vendoring is the same pattern already used for CLAIMABLE_LANES in
// cloud/functions/index.js (see conductor/tests/cloud-route-parity.test.mjs's
// TC-10), generalized into a generator + freshness assertion instead of a
// hand-copied literal, per D1/D4: this is a generated-and-asserted artifact,
// not a second hand-kept list.
//
// Usage:
//   node conductor/scripts/vendor-collector-manifest.mjs           # writes the vendored file
//   node conductor/scripts/vendor-collector-manifest.mjs --check   # exits 1 if the checked-in copy is stale

import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SOURCE_PATH = join(repoRoot, 'conductor/services/collector-manifest.mjs');
const OUTPUT_PATH = join(repoRoot, 'cloud/functions/collector-manifest.js');

const BANNER = `// cloud/functions/collector-manifest.js
// DO NOT EDIT — generated by conductor/scripts/vendor-collector-manifest.mjs
// from conductor/services/collector-manifest.mjs (Track 10061, D4).
//
// Firebase deploys cloud/functions/ standalone (functions.source in
// firebase.json), so it cannot require() anything under conductor/, and the
// cloud function is CommonJS while the canonical source is ESM. This is a
// mechanical export -> module.exports transform of that source — regenerate
// it with the command above instead of editing this file. A test
// (conductor/tests/track-10061-collector-manifest.test.mjs) regenerates this
// into memory and asserts it is byte-identical to what's checked in; drift
// fails the suite. A firebase.json predeploy hook also regenerates it, so a
// deploy cannot ship a stale copy even if someone skipped the test.
`;

/**
 * Mechanical ESM -> CommonJS transform. Deliberately narrow — it only
 * understands the constructs collector-manifest.mjs actually uses (named
 * `export const`/`export function`, and a single `import { ... } from '...'`
 * of another vendorable local module), so that anyone changing the source in
 * a way this transform can't follow gets a loud parse failure here rather
 * than a silently wrong vendored file.
 *
 * @param {string} source contents of collector-manifest.mjs
 * @returns {string} CommonJS source
 */
export function transformToCommonJs(source) {
  const exportNames = [];

  let out = source;

  // import { a, b } from './local-module.mjs';  ->  const { a, b } = require('./local-module');
  out = out.replace(
    /^import\s*\{([^}]+)\}\s*from\s*['"]\.\/([^'"]+)\.mjs['"];\s*$/gm,
    (_m, names, mod) => `const {${names}} = require('./${mod}');`,
  );

  // export const NAME = ...;
  out = out.replace(/^export const (\w+)/gm, (_m, name) => {
    exportNames.push(name);
    return `const ${name}`;
  });

  // export function name(...) { ... }
  out = out.replace(/^export function (\w+)/gm, (_m, name) => {
    exportNames.push(name);
    return `function ${name}`;
  });

  if (exportNames.length === 0) {
    throw new Error('vendor-collector-manifest: transform found no exports — source shape changed unexpectedly');
  }

  out += `\nmodule.exports = { ${exportNames.join(', ')} };\n`;
  return out;
}

export function buildVendoredFile() {
  const source = readFileSync(SOURCE_PATH, 'utf8');
  return BANNER + '\n' + transformToCommonJs(source);
}

function main() {
  const checkOnly = process.argv.includes('--check');
  const generated = buildVendoredFile();

  if (checkOnly) {
    let current = null;
    try {
      current = readFileSync(OUTPUT_PATH, 'utf8');
    } catch {
      // Treat "missing" as stale — falls through to the mismatch report below.
    }
    if (current === generated) {
      console.log('✅ cloud/functions/collector-manifest.js is up to date');
      process.exit(0);
    }
    console.error(
      '❌ cloud/functions/collector-manifest.js is stale — run:\n' +
        '   node conductor/scripts/vendor-collector-manifest.mjs',
    );
    process.exit(1);
  }

  writeFileSync(OUTPUT_PATH, generated);
  console.log(`✅ Wrote ${OUTPUT_PATH}`);
}

// Only run when invoked directly (`node vendor-collector-manifest.mjs`), not
// when imported by the freshness test.
if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
